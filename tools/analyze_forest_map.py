"""Generate Qt centerlines and fixed deployment slots for the supplied map."""
from pathlib import Path
import math
from PIL import Image, ImageDraw
ROOT = Path(__file__).resolve().parents[1]
COLS, ROWS = 46, 23
im = Image.open(ROOT/'assets/maps/forest_route_clean.png').convert('RGB')
assert im.size == (1774,887), 'Recalibrate geometry for a different map'
CW,CH = im.width/COLS, im.height/ROWS
# Authored deployment regions retained after the meadow visuals were removed.
MEADOWS = [(272,280,329,326),(439,384,504,422),(613,409,667,449),
(380,531,440,565),(504,526,551,563),(680,532,744,562),(731,260,769,293),
(1150,286,1216,329),(1329,349,1382,389),(1152,466,1200,502),
(991,583,1038,619),(868,659,918,695),(710,664,747,694)]
def route(start, commands):
    points=[start]
    for command in commands:
        p=points[-1]
        end=command[-2:]
        control=command[:2] if len(command)==4 else None
        length=math.dist(p,end) if control is None else math.dist(p,control)+math.dist(control,end)
        steps=max(1,math.ceil(length/6))
        for i in range(1,steps+1):
            t=i/steps
            if control:
                points.append(tuple((1-t)**2*p[k]+2*(1-t)*t*control[k]+t*t*end[k] for k in (0,1)))
            else:
                points.append(tuple(p[k]+(end[k]-p[k])*t for k in (0,1)))
    return points
# Dense quadratic bends prevent cutting across the inside of corners.
shared=route((931,416),[(1205,416),(1273,416,1273,350),(1273,269),
(1273,214,1325,214),(1385,214),(1437,214,1437,267),(1437,410),
(1437,451,1475,451),(1515,451,1515,491),(1515,549),
(1515,599,1565,599),(1677,599),(1677,557)])
cave=route((139,116),[(139,190),(139,230,180,230),(330,230),
(382,230,382,280),(382,416),(382,474,440,474),(500,474),
(562,474,562,414),(562,402),(562,358,610,358),(630,358),
(683,358,683,310),(683,267),(683,214,733,214),(876,214),
(931,214,931,271),(931,416)])+shared[1:]
den=route((655,886),[(655,686),(655,613,715,613),(875,613),
(931,613,931,561),(931,416)])+shared[1:]
paths=[[(round(x/CW-.5,6),round(y/CH-.5,6)) for x,y in points] for points in (cave,den)]
road=Image.new('1',im.size)
rd=ImageDraw.Draw(road)
for points in (cave,den): rd.line(points,fill=1,width=58)
selected=set()
for a,b,c,d in MEADOWS:
    candidates=[(x,y) for y in range(ROWS) for x in range(COLS)
                if a+1<=(x+.5)*CW<=c-1 and b+1<=(y+.5)*CH<=d-1]
    assert candidates, 'Every meadow needs a deployment slot'
    selected.add(min(candidates,key=lambda p: ((p[0]+.5)*CW-(a+c)/2)**2+((p[1]+.5)*CH-(b+d)/2)**2))
rows=[]; spots=[]
for y in range(ROWS):
    row=''
    for x in range(COLS):
        px,py=(x+.5)*CW,(y+.5)*CH
        meadow=(x,y) in selected
        if meadow:
            row+='G'; spots.append((x,y))
        else: row+='#' if road.getpixel((int(px),int(py))) else '.'
    rows.append(row)
assert len(spots)>=10
assert all(len(row)==COLS for row in rows)
header='''#pragma once
// Generated by tools/analyze_forest_map.py. G = fixed deployment slot.
// pixel = (grid + 0.5) * cell; all paths follow the authored centerline.
#include <vector>
#include "Position.h"
namespace ForestMap {
const int WIDTH = 46;
const int HEIGHT = 23;
inline const char* const* terrainRows() {
    static const char* rows[] = {
'''
header+='\n'.join('        "%s",'%row for row in rows)+'\n        nullptr\n    };\n    return rows;\n}\n'
for name,points in zip(('pathCave','pathDen'),paths):
    header+='inline std::vector<FWaypoint> %s() {\n    return {\n'%name
    header+='\n'.join('        {%.6f, %.6f},'%p for p in points)+'\n    };\n}\n'
header+='} // namespace ForestMap\n'
(ROOT/'core/ForestMapData.h').write_text(header,encoding='utf-8')
draw=ImageDraw.Draw(im)
for points in (cave,den): draw.line(points,fill='#ff32cb',width=4)
for x,y in spots:
    px,py=(x+.5)*CW,(y+.5)*CH
    draw.ellipse((px-13,py-13,px+13,py+13),outline='#ffff80',width=3)
im.save(ROOT/'assets/maps/_terrain_analysis.png')
print('Deployment cells:',len(spots),'Route samples:',[len(p) for p in paths])
